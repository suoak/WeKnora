test('active space switching uses one knowledge-base landing without widening tenant scope', () => {
  const switcher = source('./SpaceSwitcher.vue')
  const tenantSelector = source('./TenantSelector.vue')
  const switchFlow = source('../utils/tenantSwitch.ts')
  const policy = source('../utils/tenantSwitchPolicy.ts')
  const navigation = source('../config/navigation.ts')
  const portal = source('../views/portal/PortalHome.vue')
  assert.match(switcher, /const memberships = computed\(\(\) => authStore\.memberships \|\| \[\]\)/)
  assert.match(switcher, /v-for="membership in filtered"/)
  assert.match(switcher, /if \(isCurrent\(membership\.tenant_id\)\)/)
  assert.doesNotMatch(switcher + tenantSelector, /window\.location|router\.(?:push|replace)/)
  assert.match(switcher, /switchWorkspaceAndNavigate/)
  assert.match(tenantSelector, /switchWorkspaceAndNavigate/)
  assert.match(switchFlow, /navigateAfterTenantSwitch\(target\.targetPath\)/)
  assert.match(switchFlow, /restorePreviousTenant\(\)/)
  assert.match(switchFlow, /consumePendingTenantSwitchToast\(\)/)
  assert.match(switchFlow, /catch \{[\s\S]*restorePreviousTenant\(\)[\s\S]*target\.onNavigationFailure\?\.\(\)/)
  assert.match(policy, /TENANT_SWITCH_FALLBACK = '\/platform\/knowledge-bases'/)
  assert.doesNotMatch(policy, /TENANT_SWITCH_FALLBACK = '\/portal'/)
  assert.match(portal, /targetPath:'\/platform\/knowledge-bases'/)
  assert.match(navigation, /id: 'portal'[^\n]*route: '\/portal'/)
  assert.match(navigation, /id: 'knowledge-bases'[^\n]*route: '\/platform\/knowledge-bases'/)
})

