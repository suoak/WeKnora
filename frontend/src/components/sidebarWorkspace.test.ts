test('sidebar IA distinguishes Portal home, current space, and space-scoped resources', () => {
  const navigation = source('../config/navigation.ts')
  const zh = source('../i18n/locales/zh-CN.ts')
  const en = source('../i18n/locales/en-US.ts')
  const switcher = source('./SpaceSwitcher.vue')
  const adminSwitcher = source('./TenantSelector.vue')
  assert.match(zh, /portalHome: '首页'/)
  assert.doesNotMatch(zh, /portalHome: '知识门户'/)
  assert.match(zh, /knowledgeBases: '空间知识库'/)
  assert.match(zh, /members: '空间成员'/)
  assert.match(en, /knowledgeBases: 'Space Knowledge Bases'/)
  assert.match(en, /members: 'Space Members'/)
  assert.match(navigation, /id: 'knowledge-bases'[\s\S]*route: '\/platform\/knowledge-bases'/)
  assert.match(navigation, /id: 'knowledge-bases'[\s\S]*icon: 'knowledge-base'/)
  assert.match(switcher, /authStore\.currentTenantName/)
  assert.match(switcher, /spaceSwitcher\.currentSpace/)
  assert.match(switcher, /switchWorkspaceAndNavigate/)
  assert.match(switcher, /const canSwitch = computed\(\(\) => memberships\.value\.length > 1\)/)
  assert.match(switcher, /v-if="canSwitch" name="chevron-down"/)
  assert.match(switcher, /v-if="open && canSwitch"/)
  assert.match(adminSwitcher, /spaceSwitcher\.currentSpace/)
  const sidebar = source('./SidebarNavigation.vue')
  assert.match(sidebar, /v-if="group\.id === 'global' && authStore\.effectiveTenantId" class="nav-group space-context"/)
  assert.ok(
    sidebar.indexOf("group.id === 'global' && authStore.effectiveTenantId") < sidebar.indexOf('<section class="nav-group">'),
    'current-space context should render before the Home navigation group',
  )
  assert.match(sidebar, /TenantSelector v-if="authStore\.canAccessAllTenants && !collapsed"/)
  assert.match(sidebar, /SpaceSwitcher v-else-if="!collapsed"/)
  assert.match(sidebar, /entry\.id === 'knowledge-bases'[\s\S]*nav-entry__knowledge-icon/)
  assert.match(sidebar, /zhishiku\.svg/)
  assert.doesNotMatch(sidebar, /currentTenantRole[^\n]*(SpaceSwitcher|TenantSelector)|(SpaceSwitcher|TenantSelector)[^\n]*currentTenantRole/)
})

