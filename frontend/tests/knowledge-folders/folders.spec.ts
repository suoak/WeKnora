import { expect, test } from '@playwright/test'
const path='/tests/knowledge-folders/index.html'
test.beforeAll(async({request})=>{
 const endpoint='http://127.0.0.1:18088/api/v1/knowledge-bases/kb-1/knowledge/folders'
 const response=await request.get(endpoint)
 expect(response.ok()).toBeTruthy()
 const tree=await response.json()
 const clear=async(nodes:any[])=>{for(const node of nodes){await clear(node.children||[]);expect((await request.delete(endpoint+'/empty',{params:{path:node.path}})).ok()).toBeTruthy()}}
 await clear(tree.data.folders)
})
test('real components create and retain nested empty folders, rename and delete leaves',async({page})=>{
 await page.goto(path,{waitUntil:'domcontentloaded'})
 const create=async(name:string)=>{
  await page.getByRole('button',{name:'新建文件夹',exact:true}).last().click()
  await page.locator('#document-folder-name').fill(name)
  await page.locator('.document-folder-create-dialog').getByRole('button',{name:'新建文件夹'}).click()
  await expect(page.locator('#document-folder-name')).toBeHidden({timeout:15000})
 }
 await create('空目录')
 await page.locator('.kb-folder-row').filter({hasText:'空目录'}).click()
 await create('二级')
 await page.locator('.kb-folder-row').filter({hasText:'二级'}).click()
 await create('三级')
 await page.reload({waitUntil:'domcontentloaded'})
 await page.locator('.kb-folder-row').filter({hasText:'二级'}).locator('.kb-folder-row__toggle').click()
 await expect(page.locator('.kb-folder-row__label',{hasText:'三级'})).toBeVisible()
 await expect(page.getByText('文档总数：0')).toBeVisible()
 await page.screenshot({path:'test-results/knowledge-folders/nested-empty.png',fullPage:true})
 const leaf=page.locator('.kb-folder-row').filter({hasText:'三级'})
 await leaf.locator('.kb-folder-row__more').click()
 await page.getByText('重命名',{exact:true}).click()
 await leaf.locator('input').fill('已重命名')
 await leaf.locator('input').press('Enter')
 await expect(page.locator('.kb-folder-row__label',{hasText:'已重命名'})).toBeVisible()
 await page.reload({waitUntil:'domcontentloaded'})
 await page.locator('.kb-folder-row').filter({hasText:'二级'}).locator('.kb-folder-row__toggle').click()
 const renamed=page.locator('.kb-folder-row').filter({hasText:'已重命名'})
 await renamed.locator('.kb-folder-row__more').click()
 await page.getByText('删除空文件夹',{exact:true}).click()
 await expect(page.locator('.kb-folder-row__label',{hasText:'已重命名'})).toHaveCount(0)
 await page.reload({waitUntil:'domcontentloaded'})
 await expect(page.locator('.kb-folder-row__label',{hasText:'二级'})).toBeVisible()
})
test('picker persists newly created destinations and viewers have no creation controls',async({page})=>{
 await page.goto(path,{waitUntil:'domcontentloaded'})
 await page.getByText('移动目标选择器').click()
 await page.locator('.folder-picker__add').first().click()
 await page.locator('.folder-picker__input').fill('选择器持久目录')
 await page.locator('.folder-picker__input').press('Enter')
 await expect(page.locator('.kb-folder-row__label',{hasText:'选择器持久目录'})).toBeVisible()
 await page.reload({waitUntil:'domcontentloaded'})
 await expect(page.locator('.kb-folder-row__label',{hasText:'选择器持久目录'})).toBeVisible()
 await page.goto(path+'?viewer',{waitUntil:'domcontentloaded'})
 await expect(page.getByRole('button',{name:'新建文件夹',exact:true})).toHaveCount(0)
 await expect(page.locator('.kb-folder-row__more')).toHaveCount(0)
 await page.screenshot({path:'test-results/knowledge-folders/viewer.png',fullPage:true})
})
