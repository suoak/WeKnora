import { test, expect } from '@playwright/test'
import { keyFixture, openKey, chooseClient } from './fixtures'

test('Key list, seven bound client formats, clipboard, history and responsive themes', async ({ page }) => {
  const api = await keyFixture(page)
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/platform/mcp-access')
  await expect(page.locator('.personal-key-card')).toHaveCount(5)
  await expect(page.locator('.personal-key-card').first()).toHaveAttribute('data-key-id', '3')
  await expect(page.locator('.personal-surface .t-select')).toHaveCount(0)
  await expect(page.locator('.client-grid')).toHaveCount(0)
  await expect(page.locator('.history-surface')).toContainText('历史接入 · 19 个凭证')
  await page.screenshot({ path: 'test-results/mcp-access/desktop-light.png', fullPage: true })
  for (const name of ['Claude Code', 'Codex', 'GitHub Copilot', 'VS Code', 'WorkBuddy', 'Pi', '其他 MCP 客户端']) {
    await openKey(page, 3)
    const dialog = page.locator('.t-dialog:visible')
    await expect(dialog.locator('.client-picker button')).toHaveCount(7)
    await expect(dialog).not.toContainText('Cursor')
    await expect(dialog).not.toContainText('WorkMate')
    await expect(dialog.locator('.t-select')).toHaveCount(0)
    await chooseClient(page, name)
    await expect(dialog).toContainText('默认知识 Key')
    await expect(dialog).toContainText('客户端待验证')
    await expect(dialog).not.toContainText('synthetic-key-3')
    expect(api.reveals).toHaveLength(0)
    await dialog.getByRole('button', { name: '复制完整配置（含密钥）', exact: true }).click()
    await expect.poll(() => api.reveals.length).toBe(1)
    const copied = (await page.evaluate(() => navigator.clipboard.readText())).replaceAll('\r\n', '\n')
    expect(copied).toContain('/api/v1/mcp/personal')
    if (name === 'Codex') { expect(copied).toContain('[mcp_servers.'); expect(copied).toContain('Authorization = "Bearer synthetic-key-3"') }
    else {
      const config = JSON.parse(copied)
      expect(Boolean(config.servers)).toBe(name === 'VS Code' || name === 'GitHub Copilot')
      expect((config.servers?.knowhub || config.mcpServers.knowhub).headers.Authorization).toBe('Bearer synthetic-key-3')
    }
    await expect(dialog).not.toContainText('synthetic-key-3')
    await dialog.getByRole('button', { name: '复制 Secret', exact: true }).click()
    await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe('synthetic-key-3')
    await page.mouse.move(0, 0)
    await expect(page.locator('.t-message')).toHaveCount(0, { timeout: 10000 })
    await page.screenshot({ path: `test-results/mcp-access/client-${name.replaceAll(' ', '-')}.png`, animations: 'disabled' })
    await dialog.locator('.t-dialog__close').click()
    api.reveals.length = 0
  }
  await page.getByPlaceholder('搜索 Key 名称').fill('指定')
  await expect(page.locator('.personal-key-card')).toHaveCount(1)
  await expect(page.locator('.personal-key-card')).toHaveAttribute('data-key-id', '4')
  await page.getByPlaceholder('搜索 Key 名称').fill('')
  for (const status of ['已过期', '已停用']) {
    await page.locator('.personal-surface .status-tabs').locator('.t-tabs__nav-item').filter({ hasText: new RegExp(status) }).click()
    await expect(page.locator('.personal-key-card')).toHaveCount(1)
    await expect(page.locator('.personal-key-card').getByRole('button', { name: '连接 AI 工具' })).toBeDisabled()
  }
  await page.locator('.personal-surface .status-tabs').locator('.t-tabs__nav-item').filter({ hasText: /全部/ }).click()
  await page.locator('.personal-surface .t-pagination__number').filter({ hasText: /^2$/ }).click()
  await expect(page.locator('.personal-key-card')).toHaveCount(3)
  await page.locator('.personal-surface .t-pagination__number').filter({ hasText: /^1$/ }).click()
  await page.getByRole('button', { name: /历史接入 ·/ }).click()
  await expect(page.locator('.history-surface .credential-card')).toHaveCount(5)
  await expect(page.locator('.history-surface')).toContainText('Cursor')
  await expect(page.locator('.history-surface')).toContainText('WorkMate')
  await expect(page.locator('.history-surface')).not.toContainText('默认知识 Key')
  await page.screenshot({ path: 'test-results/mcp-access/history-expanded.png', fullPage: true })
  await page.locator('.history-surface .t-pagination__number').filter({ hasText: /^4$/ }).click()
  await expect(page.locator('.history-surface .credential-card')).toHaveCount(4)
  const manage = page.locator('.history-surface .credential-card').last().getByRole('button', { name: '管理', exact: true })
  await manage.scrollIntoViewIfNeeded()
  await expect(manage).toBeInViewport()
  await page.screenshot({ path: 'test-results/mcp-access/history-last-page.png', fullPage: true })
  await page.locator('.history-surface .status-tabs').locator('.t-tabs__nav-item').filter({ hasText: /已过期/ }).click()
  await expect(page.locator('.history-surface .credential-card')).toHaveCount(1)
  await page.getByRole('button', { name: /历史接入 ·/ }).click()
  for (const [width, theme] of [[1440, 'dark'], [1024, 'light'], [768, 'dark'], [390, 'light']] as const) {
    await page.setViewportSize({ width, height: 900 })
    await page.evaluate(value => document.documentElement.setAttribute('theme-mode', value), theme)
    expect(await page.locator('html').evaluate(el => getComputedStyle(el).filter)).toBe('none')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.locator('.mcp-access-center').evaluate(el => { el.scrollTop = 0 })
    await page.screenshot({ path: `test-results/mcp-access/${width}-${theme}.png`, animations: 'disabled', fullPage: true })
    await openKey(page, 3)
    expect(await page.locator('.monochrome-icon').evaluate(el => getComputedStyle(el).filter)).toBe(theme === 'dark' ? 'invert(1)' : 'none')
    await page.screenshot({ path: `test-results/mcp-access/picker-${width}-${theme}.png`, animations: 'disabled' })
    await page.locator('.t-dialog:visible .t-dialog__close').click()
    const history = page.getByRole('button', { name: /历史接入 ·/ })
    await history.scrollIntoViewIfNeeded()
    await expect(history).toBeInViewport()
  }
  await page.setViewportSize({ width: 1366, height: 768 })
  for (const zoom of [1, 1.25, 1.5]) {
    await page.evaluate(value => { document.documentElement.style.zoom = String(value) }, zoom)
    await openKey(page, 3)
    await chooseClient(page, 'Pi')
    const dialog = page.locator('.t-dialog:visible')
    await dialog.getByRole('button', { name: '复制完整配置（含密钥）', exact: true }).scrollIntoViewIfNeeded()
    await expect(dialog.getByRole('button', { name: '复制完整配置（含密钥）', exact: true })).toBeInViewport()
    await expect(dialog.locator('.t-dialog__close')).toBeInViewport()
    const bounds = await dialog.boundingBox()
    expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(768)
    await dialog.locator('.config-steps li').last().scrollIntoViewIfNeeded()
    await expect(dialog.locator('.config-steps li').last()).toBeInViewport()
    await page.screenshot({ path: `test-results/mcp-access/1366-zoom-${zoom}.png`, animations: 'disabled' })
    await dialog.locator('.t-dialog__close').click()
  }
  expect(api.mutations).toEqual([])
  expect(api.pageErrors).toEqual([])
})
