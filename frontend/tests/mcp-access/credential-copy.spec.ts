import { test, expect } from '@playwright/test'
import { keyFixture, openKey, chooseClient } from './fixtures'

test('VS Code and Copilot complete copies contain the selected Key without input placeholders', async ({ page }) => {
  const api = await keyFixture(page)
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/platform/mcp-access')
  for (const [id, client] of [[3, 'GitHub Copilot'], [4, 'VS Code']] as const) {
    await openKey(page, id)
    await chooseClient(page, client)
    const dialog = page.locator('.t-dialog:visible')
    await expect(dialog).toContainText('用户级 MCP 配置')
    await dialog.getByRole('button', { name: '复制完整配置（含密钥）', exact: true }).click()
    await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toContain(`Bearer synthetic-key-${id}`)
    const text = await page.evaluate(() => navigator.clipboard.readText())
    const config = JSON.parse(text)
    expect(config.servers.knowhub.headers.Authorization).toBe(`Bearer synthetic-key-${id}`)
    expect(config.inputs).toBeUndefined()
    expect(text).not.toContain('${input:')
    expect(text).not.toContain('<YOUR_MCP_KEY>')
    await expect(dialog).not.toContainText(`synthetic-key-${id}`)
    await page.screenshot({ path: `test-results/mcp-access/complete-${client.replaceAll(' ', '-')}.png`, animations: 'disabled' })
    await dialog.locator('.t-dialog__close').click()
  }
  expect(api.reveals).toEqual([3, 4])
})

test('unrecoverable Key never offers a complete configuration', async ({ page }) => {
  const api = await keyFixture(page)
  api.rows[2].secret_available = false
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/platform/mcp-access')
  await openKey(page, 3)
  await chooseClient(page, 'Pi')
  const dialog = page.locator('.t-dialog:visible')
  await expect(dialog.getByRole('button', { name: '复制完整配置（含密钥）', exact: true })).toHaveCount(0)
  await expect(dialog).toContainText('占位模板不是完整配置')
  await dialog.getByRole('button', { name: '复制占位模板（需已有密钥）', exact: true }).click()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toContain('<YOUR_MCP_KEY>')
  expect(api.reveals).toEqual([])
  await dialog.getByRole('button', { name: '更换客户端', exact: true }).click()
  await chooseClient(page, 'Claude Code')
  await dialog.getByRole('button', { name: '复制占位模板（需已有密钥）', exact: true }).click()
  const config = await page.evaluate(() => navigator.clipboard.readText())
  expect(config).toContain('<YOUR_MCP_KEY>')
  expect(config).not.toContain('synthetic-key-3')
  expect(api.reveals).toEqual([])
})

test('failed reveal cannot copy or retain a previous Key Secret', async ({ page }) => {
  const api = await keyFixture(page)
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  let failedReveals = 0
  await page.route('**/mcp-api-keys/3/reveal', route => { failedReveals++; return route.fulfill({ status: 503, json: { success: false, message: 'synthetic reveal failure' } }) })
  await page.goto('/platform/mcp-access')
  await openKey(page, 4)
  await chooseClient(page, 'Pi')
  const dialog = page.locator('.t-dialog:visible')
  await dialog.getByRole('button', { name: '显示 Secret', exact: true }).click()
  await expect(dialog).toContainText('synthetic-key-4')
  await dialog.locator('.t-dialog__close').click()
  await openKey(page, 3)
  await chooseClient(page, 'Pi')
  await page.evaluate(() => navigator.clipboard.writeText('unchanged clipboard sentinel'))
  await dialog.getByRole('button', { name: '复制完整配置（含密钥）', exact: true }).click()
  await expect.poll(() => failedReveals).toBe(1)
  await expect(dialog.getByRole('button', { name: '复制完整配置（含密钥）', exact: true })).toBeEnabled()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('unchanged clipboard sentinel')
  await expect(dialog).not.toContainText('synthetic-key-4')
  await expect(dialog.locator('pre')).toContainText('<YOUR_MCP_KEY>')
  expect(api.pageErrors).toEqual([])
})

test('the existing HTTP MCP address supports complete credential copies', async ({ page }) => {
  const api = await keyFixture(page)
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.route('**/api/v1/mcp-api-keys**', route => route.fulfill({ json: { success: true, data: route.request().url().endsWith('/reveal') ? { token: 'synthetic-key-3' } : route.request().url().includes('scope-options') ? [] : api.rows, mcp_public_url: 'http://172.30.232.42/api/v1/mcp/personal' } }))
  await page.goto('/platform/mcp-access')
  await openKey(page, 3)
  await chooseClient(page, 'Claude Code')
  const dialog = page.locator('.t-dialog:visible')
  await expect(dialog.getByRole('button', { name: '显示 Secret', exact: true })).toBeEnabled()
  await expect(dialog.getByRole('button', { name: '验证 MCP 协议', exact: true })).toBeEnabled()
  await dialog.getByRole('button', { name: '复制完整配置（含密钥）', exact: true }).click()
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toContain('Bearer synthetic-key-3')
  await dialog.getByRole('button', { name: '更换客户端', exact: true }).click()
  await chooseClient(page, 'Pi')
  await expect(dialog.getByRole('button', { name: '复制完整配置（含密钥）', exact: true })).toBeEnabled()
  expect(api.reveals).toEqual([])
  await page.screenshot({ path: 'test-results/mcp-access/http-config.png', animations: 'disabled' })
})
